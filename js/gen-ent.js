/*
 * Генераторы задач для тем ЕНТ: у темы банк из 6 задач, а ученик, который занимается каждый день, проходит его за неделю.
 * Генератор собирает новую задачу из случайных чисел: верный ответ считается по формуле, а неверные варианты —
 * это типичные ошибки (с меткой ошибки мышления, если она есть). Тексты — на языке, выбранном в момент генерации.
 * Ответы проверяются в tests-academy.html независимо от решения: подстановкой, пересчётом, численно.
 */
(function () {
  const T = window.Tamyr;
  const { num, dec, frac, ri, pick, near, build, tr } = T.genKit;

  const SUP = { 0: '⁰', 1: '¹', 2: '²', 3: '³', 4: '⁴', 5: '⁵', 6: '⁶', 7: '⁷', 8: '⁸', 9: '⁹', '-': '⁻', '−': '⁻' };
  const sup = n => String(n).split('').map(c => SUP[c] || c).join('');
  const sub = n => String(n).split('').map(c => '₀₁₂₃₄₅₆₇₈₉'[c] || c).join('');
  const xp = p => (p === 0 ? '' : p === 1 ? 'x' : 'x' + sup(p));
  /* Многочлен из слагаемых [коэффициент, степень]: [[2, 2], [−3, 1], [1, 0]] → «2x² − 3x + 1». Нули пропускаем. */
  function poly(terms) {
    let out = '';
    terms.forEach(([c, p]) => {
      if (!c) return;
      const a = Math.abs(c), body = p === 0 ? String(a) : (a === 1 ? '' : a) + xp(p);
      out += out ? (c < 0 ? ' − ' : ' + ') + body : (c < 0 ? '−' : '') + body;
    });
    return out || '0';
  }
  const pt = (x, y) => `(${num(x)}; ${num(y)})`;
  const pair = (a, b) => { const [lo, hi] = a < b ? [a, b] : [b, a]; return tr(`${num(lo)} и ${num(hi)}`, `${num(lo)} және ${num(hi)}`); };
  const nz = (r, lo, hi) => { let v = 0; while (!v) v = ri(r, lo, hi); return v; };
  const TRIPLES = [[3, 4, 5], [6, 8, 10], [5, 12, 13], [8, 15, 17], [9, 12, 15], [7, 24, 25]];
  const solveText = () => tr('Решите уравнение:', 'Теңдеуді шешіңіз:'); // язык — на момент генерации, а не загрузки файла
  const calc = () => tr('Вычислите:', 'Есептеңіз:');

  T.genKit.sup = sup; T.genKit.sub = sub; T.genKit.poly = poly; T.genKit.pt = pt; T.genKit.pair = pair; T.genKit.nz = nz; T.genKit.TRIPLES = TRIPLES;

  const G = {
    pow(r) {
      const v = ri(r, 0, 3);
      if (v === 0) {
        const a = ri(r, 2, 5), n = a === 2 ? ri(r, 3, 6) : ri(r, 2, 4), res = a ** n;
        return build('pow', `${a}${sup(n)} = ?`, num(res), [[num(a * n), 'pow_as_mult'], [num(a ** (n - 1))], [num(a + n)]].concat(near(res)),
          [tr(`${a}${sup(n)} — это ${a}, умноженное само на себя ${n} ${n < 5 ? 'раза' : 'раз'}`, `${a}${sup(n)} — ${a} санын өзіне-өзін ${n} рет көбейту`),
            `${Array(n).fill(a).join(' · ')} = ${res}`]);
      }
      if (v === 1) {
        const m = ri(r, 2, 6), k = ri(r, 2, 6);
        return build('pow', `${tr('Упростите:', 'Ықшамдаңыз:')} x${sup(m)} · x${sup(k)}`, xp(m + k),
          [[xp(m * k), 'pow_mult_exp'], ['2' + xp(m + k)], [xp(Math.abs(m - k) || 1)], ['2' + xp(m * k)], [xp(m + k + 1)], [xp(m + k - 1)]],
          [tr('Основания одинаковые — показатели складываем', 'Негіздері бірдей — көрсеткіштерін қосамыз'), `x${sup(m)} · x${sup(k)} = x${sup(m)}⁺${sup(k)} = ${xp(m + k)}`]);
      }
      if (v === 2) {
        const a = ri(r, 2, 9);
        return build('pow', `(−${a})² = ?`, num(a * a), [[num(-a * a), 'neg_square'], [num(2 * a), 'pow_as_mult'], [num(-2 * a)]].concat(near(a * a)),
          [tr('Квадрат — произведение двух одинаковых множителей', 'Квадрат — екі бірдей көбейткіштің көбейтіндісі'),
            tr(`(−${a}) · (−${a}) = ${a * a}: минус на минус даёт плюс`, `(−${a}) · (−${a}) = ${a * a}: минусты минусқа көбейткенде плюс шығады`)]);
      }
      const m = ri(r, 2, 5), k = ri(r, 2, 4);
      return build('pow', `${tr('Упростите:', 'Ықшамдаңыз:')} (x${sup(m)})${sup(k)}`, xp(m * k),
        [[xp(m + k)], [k + xp(m)], [xp(m ** k)], [xp(m * k + 1)], [xp(m * k - 1)], [k + xp(m * k)]],
        [tr('Степень возводим в степень — показатели перемножаем', 'Дәрежені дәрежеге шығарғанда көрсеткіштер көбейтіледі'), `${m} · ${k} = ${m * k}`, xp(m * k)]);
    },

    root(r) {
      const v = ri(r, 0, 2);
      if (v === 0) {
        const a = ri(r, 4, 15);
        return build('root', `√${a * a} = ?`, num(a), [[dec(a * a / 2), 'root_as_half'], [num(2 * a)], [num(a * a)]].concat(near(a)),
          [tr(`Ищем число, квадрат которого равен ${a * a}`, `Квадраты ${a * a}-ға тең санды іздейміз`), `${a}² = ${a * a}  ⇒  √${a * a} = ${a}`]);
      }
      if (v === 1) {
        const [p, q, c] = pick(r, TRIPLES);
        return build('root', `√(${p * p} + ${q * q}) = ?`, num(c), [[num(p + q), 'root_of_sum'], [num(c * c)], [dec(c * c / 2), 'root_as_half']].concat(near(c)),
          [tr('Сначала считаем под корнем — корень из суммы не равен сумме корней', 'Алдымен түбір астындағыны есептейміз — қосындының түбірі түбірлердің қосындысына тең емес'),
            `${p * p} + ${q * q} = ${c * c}`, `√${c * c} = ${c}`]);
      }
      const m = pick(r, [2, 3, 5, 6, 7]), k = ri(r, 2, 6), N = k * k * m;
      return build('root', `${tr('Упростите:', 'Ықшамдаңыз:')} √${N}`, `${k}√${m}`,
        [[`${m}√${k}`, 'root_extract'], [`${k * k}√${m}`, 'root_extract'], [`${k}√${k * m}`], [`${m}√${k * k}`], [`${k + 1}√${m}`], [`${k}√${m + 1}`]],
        [tr(`Ищем множитель — полный квадрат: ${N} = ${k * k} · ${m}`, `Толық квадрат болатын көбейткіш іздейміз: ${N} = ${k * k} · ${m}`),
          `√(${k * k} · ${m}) = √${k * k} · √${m} = ${k}√${m}`]);
    },

    fsu(r) {
      const v = ri(r, 0, 3), a = ri(r, 2, 9), open = tr('Раскройте скобки:', 'Жақшаны ашыңыз:');
      if (v === 0) {
        return build('fsu', `${open} (x + ${a})²`, poly([[1, 2], [2 * a, 1], [a * a, 0]]),
          [[poly([[1, 2], [a * a, 0]]), 'sq_sum_distribute'], [poly([[1, 2], [a, 1], [a * a, 0]])], [poly([[1, 2], [2 * a, 1], [2 * a, 0]])], [poly([[1, 2], [2 * a, 1], [a, 0]])], [poly([[2, 2], [2 * a, 1], [a * a, 0]])]],
          ['(a + b)² = a² + 2ab + b²', `x² + 2 · x · ${a} + ${a}² = ${poly([[1, 2], [2 * a, 1], [a * a, 0]])}`]);
      }
      if (v === 1) {
        return build('fsu', `${open} (x − ${a})²`, poly([[1, 2], [-2 * a, 1], [a * a, 0]]),
          [[poly([[1, 2], [-a * a, 0]]), 'diff_sq_wrong'], [poly([[1, 2], [-2 * a, 1], [-a * a, 0]]), 'sq_sign_last'], [poly([[1, 2], [a * a, 0]]), 'sq_sum_distribute']],
          ['(a − b)² = a² − 2ab + b²', tr(`Последнее слагаемое — квадрат, он всегда с плюсом: ${poly([[1, 2], [-2 * a, 1], [a * a, 0]])}`,
            `Соңғы қосылғыш — квадрат, ол әрқашан плюспен: ${poly([[1, 2], [-2 * a, 1], [a * a, 0]])}`)]);
      }
      if (v === 2) {
        return build('fsu', `${open} (x − ${a})(x + ${a})`, poly([[1, 2], [-a * a, 0]]),
          [[poly([[1, 2], [-2 * a, 1], [a * a, 0]]), 'diff_sq_wrong'], [poly([[1, 2], [a * a, 0]])], [poly([[1, 2], [-2 * a, 0]])], [poly([[1, 2], [2 * a, 1], [-a * a, 0]])], [poly([[1, 2], [-a, 0]])]],
          ['(a − b)(a + b) = a² − b²', `x² − ${a}² = ${poly([[1, 2], [-a * a, 0]])}`]);
      }
      const n = ri(r, 21, 89), d = ri(r, 1, 5), res = 4 * n * d;
      return build('fsu', `${calc()} ${n + d}² − ${n - d}²`, num(res), [[num(4 * d * d), 'diff_sq_wrong'], [num(2 * n * d)], [num(8 * n * d)]].concat(near(res)),
        [tr('Разность квадратов: a² − b² = (a − b)(a + b)', 'Квадраттардың айырмасы: a² − b² = (a − b)(a + b)'),
          `(${n + d} − ${n - d})(${n + d} + ${n - d}) = ${2 * d} · ${2 * n} = ${res}`]);
    },

    quad(r) {
      const v = ri(r, 0, 3);
      if (v === 0) {
        let p = nz(r, -7, 7), q = nz(r, -7, 7);
        if (p === q) q = p === 7 ? -7 : p + 1;
        if (!q) q = 2;
        const eq = poly([[1, 2], [-(p + q), 1], [p * q, 0]]) + ' = 0';
        return build('quad', `${tr('Найдите корни уравнения:', 'Теңдеудің түбірлерін табыңыз:')} ${eq}`, pair(p, q),
          [[pair(-p, -q), 'vieta_sign'], [num(Math.max(p, q)), 'quad_lose_root'], [pair(1, p * q), 'vieta_check'], [pair(p, q + 1)], [tr('Корней нет', 'Түбірі жоқ')]],
          [tr(`По теореме Виета: сумма корней ${num(p + q)}, произведение ${num(p * q)}`, `Виет теоремасы бойынша: түбірлердің қосындысы ${num(p + q)}, көбейтіндісі ${num(p * q)}`),
            tr(`Подходят ${num(p)} и ${num(q)}`, `Сәйкес келетіні: ${num(p)} және ${num(q)}`)]);
      }
      if (v === 1) {
        const k = nz(r, -9, 9);
        const eq = poly([[1, 2], [-k, 1]]) + ' = 0';
        return build('quad', `${solveText()} ${eq}`, pair(0, k),
          [[num(k), 'quad_divide_x'], [pair(0, -k)], [num(-k)], [pair(1, k)]],
          [tr(`Выносим x за скобку: x(x ${k > 0 ? '−' : '+'} ${Math.abs(k)}) = 0`, `x-ті жақша сыртына шығарамыз: x(x ${k > 0 ? '−' : '+'} ${Math.abs(k)}) = 0`),
            tr(`Произведение равно нулю, когда один из множителей равен нулю: x = 0 или x = ${num(k)}`, `Көбейтінді нөлге тең, егер көбейткіштің біреуі нөлге тең болса: x = 0 немесе x = ${num(k)}`)]);
      }
      if (v === 2) {
        const a = ri(r, 1, 3), b = nz(r, -9, 9), c = nz(r, -9, 9), D = b * b - 4 * a * c;
        const eq = poly([[a, 2], [b, 1], [c, 0]]) + ' = 0';
        return build('quad', tr(`Найдите дискриминант уравнения ${eq}`, `${eq} теңдеуінің дискриминантын табыңыз`), num(D),
          [[num(b * b + 4 * a * c), 'disc_sign'], [num(b - 4 * a * c)], [num(-b * b - 4 * a * c)]].concat(near(D)),
          [`a = ${num(a)}, b = ${num(b)}, c = ${num(c)}`, `D = b² − 4ac = ${b * b} − 4 · ${num(a)} · ${c < 0 ? '(' + num(c) + ')' : c} = ${num(D)}`]);
      }
      const n = ri(r, 2, 12);
      return build('quad', `${solveText()} x² = ${n * n}`, `x = ±${n}`,
        [[`x = ${n}`, 'quad_lose_root'], [`x = ${dec(n * n / 2)}`, 'root_as_half'], [`x = ${n * n}`], [`x = ±${n * n}`], [`x = ${2 * n}`]],
        [tr(`Число, квадрат которого равен ${n * n}: ${n}² = ${n * n} и (−${n})² = ${n * n}`, `Квадраты ${n * n}-ға тең сан: ${n}² = ${n * n} және (−${n})² = ${n * n}`), `x = ±${n}`]);
    },

    ineq(r) {
      const FLIP = { '>': '<', '<': '>', '≥': '≤', '≤': '≥' };
      const op = pick(r, ['>', '<', '≥', '≤']), a = r() < 0.6 ? -ri(r, 2, 5) : ri(r, 2, 5), x0 = ri(r, -6, 6), b = ri(r, -9, 9), c = a * x0 + b;
      const res = a < 0 ? FLIP[op] : op, ans = (o, x) => `x ${o} ${num(x)}`;
      const wrongs = a < 0
        ? [[ans(op, x0), 'ineq_flip'], [ans(res, -x0)], [ans(op, -x0)], [ans(res, x0 + 1)], [ans(op, x0 + 1)]]
        : [[ans(FLIP[op], x0)], [ans(op, -x0)], [ans(op, x0 + 1)], [ans(FLIP[op], x0 + 1)]];
      const steps = [tr('Решаем как уравнение, но при делении на отрицательное число знак неравенства меняется', 'Теңдеу сияқты шешеміз, бірақ теріс санға бөлгенде теңсіздік таңбасы өзгереді')];
      if (b) steps.push(tr(`Переносим ${num(b)} вправо со сменой знака: ${poly([[a, 1]])} ${op} ${num(c - b)}`, `${num(b)} санын таңбасын өзгертіп оң жаққа көшіреміз: ${poly([[a, 1]])} ${op} ${num(c - b)}`));
      steps.push(a < 0
        ? tr(`Делим на ${num(a)} — число отрицательное, поэтому знак неравенства меняется: x ${res} ${num(x0)}`, `${num(a)} санына бөлеміз — сан теріс, сондықтан теңсіздік таңбасы өзгереді: x ${res} ${num(x0)}`)
        : tr(`Делим на ${a}: x ${res} ${num(x0)}`, `${a} санына бөлеміз: x ${res} ${num(x0)}`));
      return build('ineq', `${tr('Решите неравенство:', 'Теңсіздікті шешіңіз:')} ${poly([[a, 1], [b, 0]])} ${op} ${num(c)}`, ans(res, x0), wrongs, steps);
    },

    sys(r) {
      const v = ri(r, 0, 2);
      if (v === 0) {
        const x = ri(r, 1, 12); let y = ri(r, 1, 12); if (y === x) y = x === 12 ? 11 : x + 1;
        return build('sys', `x + y = ${x + y}, x − y = ${num(x - y)}. ${tr('Найдите x.', 'x-ті табыңыз.')}`, num(x),
          [[num(y), 'sys_order_swap'], [num(x + y)], [num(x - y)]].concat(near(x)),
          [tr(`Складываем уравнения — y исчезает: 2x = ${2 * x}`, `Теңдеулерді қосамыз — y жойылады: 2x = ${2 * x}`), `x = ${x}`]);
      }
      if (v === 1) {
        const x = ri(r, 1, 6), k = ri(r, 2, 4), y = k * x, s = x + y;
        return build('sys', `y = ${k}x, x + y = ${s}. ${tr('Решение системы (x; y):', 'Жүйенің шешімі (x; y):')}`, pt(x, y),
          [[pt(y, x), 'sys_order_swap'], [`(${dec(s / 2)}; ${dec(s / 2)})`], [pt(x + 1, y - 1)], [pt(x, s)]],
          [tr(`Подставляем y = ${k}x во второе уравнение: x + ${k}x = ${s}`, `y = ${k}x-ті екінші теңдеуге қоямыз: x + ${k}x = ${s}`),
            tr(`x = ${x}, тогда y = ${y}`, `x = ${x}, сонда y = ${y}`)]);
      }
      const a = ri(r, 2, 4), x = ri(r, 1, 8), y = ri(r, -5, 9), c1 = a * x + y, c2 = x + y;
      return build('sys', `${a}x + y = ${num(c1)}, x + y = ${num(c2)}. ${tr('Найдите x.', 'x-ті табыңыз.')}`, num(x),
        [[num(y), 'sys_order_swap'], [num(c1 - c2)], [dec((c1 - c2) / (a + 1))]].concat(near(x)),
        [tr(`Вычитаем второе уравнение из первого: ${a - 1 === 1 ? '' : a - 1}x = ${num(c1 - c2)}`, `Бірінші теңдеуден екіншісін азайтамыз: ${a - 1 === 1 ? '' : a - 1}x = ${num(c1 - c2)}`), `x = ${x}`]);
    },

    linf(r) {
      const v = ri(r, 0, 3), k = nz(r, -5, 5);
      if (v === 2) {
        const x0 = nz(r, -6, 6), b = -k * x0, f = poly([[k, 1], [b, 0]]);
        return build('linf', tr(`В какой точке график y = ${f} пересекает ось Ox?`, `y = ${f} графигі Ox осін қай нүктеде қияды?`), pt(x0, 0),
          [[pt(0, x0), 'axis_swap'], [pt(0, b), 'axis_swap'], [pt(-x0, 0)], [pt(x0, b)]],
          [tr('На оси Ox всегда y = 0', 'Ox осінде әрқашан y = 0'), `${f} = 0  ⇒  x = ${num(x0)}`, tr(`Точка ${pt(x0, 0)}`, `Нүкте ${pt(x0, 0)}`)]);
      }
      let b = nz(r, -9, 9); if (Math.abs(b) === Math.abs(k)) b = b > 0 ? b + 1 : b - 1;
      const f = poly([[k, 1], [b, 0]]);
      if (v === 0) {
        return build('linf', tr(`В какой точке график y = ${f} пересекает ось Oy?`, `y = ${f} графигі Oy осін қай нүктеде қияды?`), pt(0, b),
          [[pt(b, 0), 'axis_swap'], [pt(0, k), 'slope_intercept'], [pt(k, 0)], [pt(0, -b)]],
          [tr('На оси Oy всегда x = 0', 'Oy осінде әрқашан x = 0'), `y = ${num(k)} · 0 ${b < 0 ? '−' : '+'} ${Math.abs(b)} = ${num(b)}`, tr(`Точка ${pt(0, b)}`, `Нүкте ${pt(0, b)}`)]);
      }
      if (v === 1) {
        return build('linf', tr(`Чему равен угловой коэффициент функции y = ${f}?`, `y = ${f} функциясының бұрыштық коэффициенті нешеге тең?`), num(k),
          [[num(b), 'slope_intercept'], [num(-k)], [num(k + b)], [frac(1, Math.abs(k)) === '1' ? num(k * 2) : (k < 0 ? '−' : '') + frac(1, Math.abs(k))]],
          [tr('В записи y = kx + b угловой коэффициент — число перед x', 'y = kx + b жазуында бұрыштық коэффициент — x-тің алдындағы сан'), `k = ${num(k)}`]);
      }
      const x0 = ri(r, -4, 4), y = k * x0 + b;
      return build('linf', tr(`y = ${f}. Найдите y при x = ${num(x0)}.`, `y = ${f}. x = ${num(x0)} болғанда y-ті табыңыз.`), num(y),
        [[num(k + x0 + b)], [num(-k * x0 + b)], [num(k * x0 - b)]].concat(near(y)),
        [tr('Подставляем x в формулу', 'x-ті формулаға қоямыз'), `y = ${num(k)} · ${x0 < 0 ? '(' + num(x0) + ')' : x0} ${b < 0 ? '−' : '+'} ${Math.abs(b)} = ${num(y)}`]);
    },

    parab(r) {
      const v = ri(r, 0, 3);
      if (v === 0) {
        const m = nz(r, -5, 5), n = ri(r, -5, 5);
        const f = `y = (x ${m > 0 ? '−' : '+'} ${Math.abs(m)})²${n ? ` ${n > 0 ? '+' : '−'} ${Math.abs(n)}` : ''}`;
        return build('parab', tr(`Координаты вершины параболы ${f}:`, `${f} параболасы төбесінің координаталары:`), pt(m, n),
          [[pt(-m, n), 'vertex_sign'], [pt(m, -n)], [pt(n, m)], [pt(-m, -n), 'vertex_sign'], [pt(m, n + 1)], [pt(-m, n + 1)]],
          [tr('Вид y = (x − m)² + n: вершина (m; n)', 'y = (x − m)² + n түрі: төбесі (m; n)'), `m = ${num(m)}, n = ${num(n)}`]);
      }
      if (v === 1) {
        const x0 = nz(r, -4, 4), b = -2 * x0, c = ri(r, -5, 5), y = q => q * q + b * q + c, f = poly([[1, 2], [b, 1], [c, 0]]);
        return build('parab', tr(`Координаты вершины параболы y = ${f}:`, `y = ${f} параболасы төбесінің координаталары:`), pt(x0, y(x0)),
          [[pt(-x0, y(-x0)), 'vertex_sign'], [pt(x0, c)], [pt(x0, -y(x0))], [pt(b, c)]],
          [tr(`Абсцисса вершины: x₀ = −b / 2a = ${num(x0)}`, `Төбенің абсциссасы: x₀ = −b / 2a = ${num(x0)}`), `y₀ = ${num(y(x0))}`]);
      }
      if (v === 2) {
        const a = nz(r, -4, 4), f = poly([[a, 2], [ri(r, -6, 6), 1], [ri(r, -6, 6), 0]]);
        const up = tr('Вверх', 'Жоғары'), down = tr('Вниз', 'Төмен');
        return build('parab', tr(`Куда направлены ветви параболы y = ${f}?`, `y = ${f} параболасының тармақтары қайда бағытталған?`), a > 0 ? up : down,
          [[a > 0 ? down : up, 'branches_sign'], [tr('Вправо', 'Оңға')], [tr('Влево', 'Солға')]],
          [tr(`Смотрим на коэффициент при x²: a = ${num(a)}`, `x²-тың коэффициентіне қараймыз: a = ${num(a)}`),
            a > 0 ? tr('a > 0 — ветви направлены вверх', 'a > 0 — тармақтары жоғары бағытталған') : tr('a < 0 — ветви направлены вниз', 'a < 0 — тармақтары төмен бағытталған')]);
      }
      const n = ri(r, 1, 9);
      return build('parab', tr(`Найдите нули функции y = x² − ${n * n}.`, `y = x² − ${n * n} функциясының нөлдерін табыңыз.`), pair(-n, n),
        [[num(n), 'quad_lose_root'], [pair(0, n)], [pair(-n * n, n * n)], [num(n * n)], [pair(-2 * n, 2 * n)]],
        [tr('Нули — там, где y = 0', 'Нөлдер — y = 0 болатын жерлер'), `x² = ${n * n}  ⇒  x = ±${n}`]);
    },

    prog(r) {
      const v = ri(r, 0, 3), ar = tr('Арифметическая прогрессия:', 'Арифметикалық прогрессия:');
      const find = n => tr(`Найдите a${sub(n)}.`, `a${sub(n)} мүшесін табыңыз.`);
      if (v === 0) {
        const a1 = ri(r, -5, 10), d = nz(r, -6, 6), n = ri(r, 4, 12), an = a1 + (n - 1) * d;
        const mix = Math.abs(a1 * d ** (n - 1)) < 1e6 ? num(a1 * d ** (n - 1)) : num(an * 2);
        return build('prog', `${ar} a₁ = ${num(a1)}, d = ${num(d)}. ${find(n)}`, num(an),
          [[num(a1 + n * d), 'prog_n'], [mix, 'prog_mix'], [num(a1 + (n - 2) * d)]].concat(near(an)),
          ['aₙ = a₁ + (n − 1)d', `a${sub(n)} = ${num(a1)} + ${n - 1} · ${d < 0 ? '(' + num(d) + ')' : d} = ${num(an)}`]);
      }
      if (v === 1) {
        const b1 = ri(r, 1, 4), q = pick(r, [2, 3, -2]), n = ri(r, 3, 6), bn = b1 * q ** (n - 1);
        return build('prog', `${tr('Геометрическая прогрессия:', 'Геометриялық прогрессия:')} b₁ = ${b1}, q = ${num(q)}. ${tr(`Найдите b${sub(n)}.`, `b${sub(n)} мүшесін табыңыз.`)}`, num(bn),
          [[num(b1 * q ** n), 'prog_n'], [num(b1 + (n - 1) * q), 'prog_mix'], [num(b1 * q * (n - 1))]].concat(near(bn)),
          ['bₙ = b₁ · qⁿ⁻¹', `b${sub(n)} = ${b1} · ${q < 0 ? '(' + num(q) + ')' : q}${sup(n - 1)} = ${num(bn)}`]);
      }
      if (v === 2) {
        const a1 = ri(r, 1, 9), d = ri(r, 1, 5), n = pick(r, [4, 6, 8, 10]), an = a1 + (n - 1) * d, S = (a1 + an) * n / 2;
        return build('prog', `${ar} a₁ = ${a1}, d = ${d}. ${tr(`Найдите сумму первых ${n} членов.`, `Алғашқы ${n} мүшесінің қосындысын табыңыз.`)}`, num(S),
          [[num(an), 'answer_wrong_qty'], [num((a1 + an) * n)], [num(n * a1 + n * d)]].concat(near(S)),
          [`a${sub(n)} = ${a1} + ${n - 1} · ${d} = ${an}`, 'Sₙ = (a₁ + aₙ) · n / 2', `S${sub(n)} = (${a1} + ${an}) · ${n} / 2 = ${S}`]);
      }
      const a1 = ri(r, -5, 9), d = nz(r, -6, 6), k = ri(r, 3, 6), ak = a1 + (k - 1) * d;
      return build('prog', `${ar} a₁ = ${num(a1)}, a${sub(k)} = ${num(ak)}. ${tr('Найдите разность прогрессии d.', 'Прогрессияның айырмасын (d) табыңыз.')}`, num(d),
        [[(ak - a1 < 0 ? '−' : '') + frac(Math.abs(ak - a1), k), 'prog_n'], [num(ak - a1)], [num(-d)]].concat(near(d)),
        [`a${sub(k)} = a₁ + ${k - 1}d`, `${num(ak)} = ${num(a1)} + ${k - 1}d  ⇒  ${k - 1}d = ${num(ak - a1)}`, `d = ${num(d)}`]);
    },

    log(r) {
      const v = ri(r, 0, 3);
      if (v === 0) {
        const b = pick(r, [2, 2, 3, 5, 10]), k = ri(r, 2, b === 2 ? 6 : b === 3 ? 4 : 3), N = b ** k;
        const head = b === 10 ? `lg ${N}` : `log${sub(b)} ${N}`;
        return build('log', `${calc()} ${head}`, num(k), [[num(N / b), 'log_as_div'], [num(N)], [num(k + 1)], [num(b * k)], [num(N + 1)], [num(k - 1)]],
          [tr(`В какую степень нужно возвести ${b}, чтобы получить ${N}?`, `${N} шығу үшін ${b} санын қандай дәрежеге шығару керек?`), `${b}${sup(k)} = ${N}  ⇒  ${head} = ${k}`]);
      }
      if (v === 1) {
        const i = ri(r, 1, 5), j = ri(r, 1, 5), A = 2 ** i, B = 2 ** j;
        return build('log', `${calc()} log₂ ${A} + log₂ ${B}`, num(i + j),
          [[`log₂ ${A + B}`, 'log_sum'], [num(i * j)], [num(A + B)], [num(i + j + 1)]],
          [tr('Сумма логарифмов с одним основанием — логарифм произведения', 'Негіздері бірдей логарифмдердің қосындысы — көбейтіндінің логарифмі'),
            `log₂ (${A} · ${B}) = log₂ ${A * B} = ${i + j}`]);
      }
      if (v === 2) {
        const b = pick(r, [2, 3, 4, 5]), k = ri(r, 2, b === 2 ? 5 : 3);
        return build('log', `${solveText()} log${sub(b)} x = ${k}`, `x = ${b ** k}`,
          [[`x = ${b * k}`, 'pow_as_mult'], [`x = ${k ** b}`], [`x = ${frac(k, b)}`], [`x = ${b ** k + 1}`], [`x = ${b ** (k + 1)}`]],
          [tr('По определению логарифма: x = основание в степени значения', 'Логарифмнің анықтамасы бойынша: x = негіздің мән дәрежесі'), `x = ${b}${sup(k)} = ${b ** k}`]);
      }
      const b = pick(r, [2, 3, 5]), a = nz(r, -6, 6);
      const e = `log${sub(b)}(x ${a > 0 ? '−' : '+'} ${Math.abs(a)})`;
      return build('log', tr(`При каких x определено выражение ${e}?`, `${e} өрнегі x-тің қандай мәндерінде анықталған?`), `x > ${num(a)}`,
        [[`x ≥ ${num(a)}`, 'log_domain'], [`x < ${num(a)}`], [`x > ${num(-a)}`], [`x ≠ ${num(a)}`]],
        [tr('Под логарифмом может стоять только положительное число', 'Логарифм астында тек оң сан тұра алады'), `x ${a > 0 ? '−' : '+'} ${Math.abs(a)} > 0  ⇒  x > ${num(a)}`]);
    },

    exp(r) {
      const v = ri(r, 0, 3), b = pick(r, [2, 3, 5]), k = ri(r, 2, b === 2 ? 6 : 3), N = b ** k;
      if (v === 0) {
        return build('exp', `${solveText()} ${b}^x = ${N}`, `x = ${k}`,
          [[`x = ${N}`, 'exp_base'], [`x = ${N / b}`], [`x = ${k + 1}`], [`x = ${b * k}`], [`x = ${k - 1}`], [`x = ${N * b}`]],
          [`${N} = ${b}${sup(k)}`, `${b}^x = ${b}${sup(k)}  ⇒  x = ${k}`]);
      }
      if (v === 1) {
        const a = ri(r, 1, 4);
        return build('exp', `${solveText()} ${b}^(x − ${a}) = ${N}`, `x = ${k + a}`,
          [[`x = ${num(k - a)}`], [`x = ${k}`], [`x = ${N + a}`, 'exp_base'], [`x = ${k * a}`], [`x = ${k + a + 1}`]],
          [`${N} = ${b}${sup(k)}  ⇒  x − ${a} = ${k}`, `x = ${k + a}`]);
      }
      if (v === 2) {
        return build('exp', `${solveText()} ${b}^x = 1/${N}`, `x = −${k}`,
          [[`x = ${k}`, 'exp_neg_power'], [`x = 1/${k}`], [tr('Корней нет', 'Түбірі жоқ'), 'exp_neg_power'], [`x = −${N}`]],
          [`1/${N} = 1/${b}${sup(k)} = ${b}${sup(-k)}`, `x = −${k}`]);
      }
      return build('exp', `${calc()} ${b}^(−${k})`, `1/${N}`,
        [[`−${N}`, 'exp_neg_power'], [`−${b * k}`], [`1/${b * k}`], [`${N}`], [`1/${2 * N}`], [`−1/${N}`]],
        [tr('Отрицательный показатель — это дробь, а не отрицательное число', 'Теріс көрсеткіш — бұл бөлшек, теріс сан емес'), `${b}${sup(-k)} = 1/${b}${sup(k)} = 1/${N}`]);
    },

    trig(r) {
      const v = ri(r, 0, 2);
      if (v === 0) {
        const V = { sin: { 0: '0', 30: '1/2', 45: '√2/2', 60: '√3/2', 90: '1' }, cos: { 0: '1', 30: '√3/2', 45: '√2/2', 60: '1/2', 90: '0' }, tg: { 0: '0', 30: '√3/3', 45: '1', 60: '√3' } };
        const f = pick(r, ['sin', 'sin', 'cos', 'cos', 'tg']), ang = pick(r, f === 'tg' ? [30, 45, 60] : [0, 30, 45, 60, 90]), val = V[f][ang];
        const wrongs = [];
        if (f !== 'tg' && (ang === 30 || ang === 60)) wrongs.push([V[f === 'sin' ? 'cos' : 'sin'][ang], 'trig_swap']);
        ['1/2', '√3/2', '√2/2', '1', '0', '√3'].forEach(x => wrongs.push([x]));
        return build('trig', `${calc()} ${f} ${ang}°`, val, wrongs,
          [tr('Для 0°, 30°, 45°, 60°, 90°: sin — 0, 1/2, √2/2, √3/2, 1; cos — те же значения в обратном порядке; tg = sin / cos',
            '0°, 30°, 45°, 60°, 90° үшін: sin — 0, 1/2, √2/2, √3/2, 1; cos — сол мәндер кері ретпен; tg = sin / cos'),
            tr(`Табличное значение: ${f} ${ang}° = ${val}`, `Кестелік мән: ${f} ${ang}° = ${val}`)]);
      }
      if (v === 1) {
        const [a, b, c] = pick(r, [[3, 4, 5], [5, 12, 13], [8, 15, 17], [7, 24, 25]]), q = r() < 0.5 ? 1 : 2;
        const cos = (q === 2 ? '−' : '') + `${b}/${c}`;
        return build('trig', tr(`sin α = ${a}/${c}, угол α ${q === 1 ? 'в первой' : 'во второй'} четверти. Найдите cos α.`, `sin α = ${a}/${c}, α бұрышы ${q === 1 ? 'бірінші' : 'екінші'} ширекте. cos α-ны табыңыз.`), cos,
          [[q === 1 ? `−${b}/${c}` : `${b}/${c}`, 'trig_sign_quarter'], [frac(c - a, c), 'trig_identity'], [`${a}/${b}`], [`${b * b}/${c * c}`]],
          [tr(`sin²α + cos²α = 1, значит cos²α = 1 − ${a * a}/${c * c} = ${b * b}/${c * c}`, `sin²α + cos²α = 1, демек cos²α = 1 − ${a * a}/${c * c} = ${b * b}/${c * c}`),
            q === 1 ? tr('В первой четверти косинус положителен', 'Бірінші ширекте косинус оң') : tr('Во второй четверти косинус отрицателен', 'Екінші ширекте косинус теріс'), `cos α = ${cos}`]);
      }
      const a = ri(r, 1, 89);
      return build('trig', `${calc()} sin²${a}° + cos²${a}°`, '1', [['0'], ['2'], [`sin ${2 * a}°`], ['1/2']],
        [tr('Основное тригонометрическое тождество: sin²α + cos²α = 1 при любом α', 'Негізгі тригонометриялық тепе-теңдік: кез келген α үшін sin²α + cos²α = 1'), `α = ${a}°:  sin²${a}° + cos²${a}° = 1`]);
    },

    deriv(r) {
      const v = ri(r, 0, 2);
      if (v === 0) {
        const a = ri(r, 2, 6), n = ri(r, 2, 5), b = ri(r, -9, 9), c = nz(r, -9, 9), f = poly([[a, n], [b, 1], [c, 0]]);
        const ok = poly([[a * n, n - 1], [b, 0]]);
        return build('deriv', `${tr('Найдите производную:', 'Туындыны табыңыз:')} f(x) = ${f}`, ok,
          [[poly([[a * n, n], [b, 0]]), 'deriv_power'], [poly([[a * n, n - 1], [b, 0], [c, 0]]), 'deriv_const'], [poly([[a, n - 1], [b, 0]])], [poly([[n, n - 1], [b, 0]])]],
          ["(xⁿ)′ = n · xⁿ⁻¹, (kx)′ = k, (const)′ = 0", `(${poly([[a, n]])})′ = ${a} · ${n}${xp(n - 1)} = ${poly([[a * n, n - 1]])}`, `f′(x) = ${ok}`]);
      }
      const a = nz(r, -4, 4), b = ri(r, -9, 9), c = nz(r, -9, 9), x0 = nz(r, -3, 3), f = poly([[a, 2], [b, 1], [c, 0]]), d = 2 * a * x0 + b;
      const text = v === 1 ? `f(x) = ${f}. ${tr(`Найдите f′(${num(x0)}).`, `f′(${num(x0)}) мәнін табыңыз.`)}`
        : tr(`Найдите угловой коэффициент касательной к графику y = ${f} в точке x₀ = ${num(x0)}.`, `y = ${f} графигіне x₀ = ${num(x0)} нүктесінде жүргізілген жанаманың бұрыштық коэффициентін табыңыз.`);
      return build('deriv', text, num(d),
        [[num(a * x0 * x0 + b * x0 + c)], [num(d + c), 'deriv_const'], [num(a * x0 + b), 'deriv_power']].concat(near(d)),
        [`f′(x) = ${poly([[2 * a, 1], [b, 0]])}`, `f′(${num(x0)}) = ${num(2 * a)} · ${x0 < 0 ? '(' + num(x0) + ')' : x0}${b ? (b < 0 ? ' − ' : ' + ') + Math.abs(b) : ''} = ${num(d)}`]
          .concat(v === 2 ? [tr('Угловой коэффициент касательной равен значению производной в точке касания', 'Жанаманың бұрыштық коэффициенті жанасу нүктесіндегі туындының мәніне тең')] : []));
    },

    integ(r) {
      const n = ri(r, 1, 3), m = ri(r, 1, 3), c = (n + 1) * m;
      if (r() < 0.55) {
        const B = ri(r, 1, n === 3 ? 2 : 3), res = m * B ** (n + 1);
        return build('integ', `${calc()} ∫₀${sup(B)} ${poly([[c, n]])} dx`, num(res),
          [[num(c * n * B ** (n - 1)), 'integ_as_deriv'], [num(c * B ** (n + 1)), 'integ_no_divide'], [num(-res), 'integ_bounds']].concat(near(res)),
          [tr(`Первообразная: F(x) = ${poly([[m, n + 1]])}`, `Алғашқы функция: F(x) = ${poly([[m, n + 1]])}`), `F(${B}) − F(0) = ${m === 1 ? '' : m + ' · '}${B}${sup(n + 1)} − 0 = ${res}`]);
      }
      return build('integ', tr(`Найдите первообразную функции f(x) = ${poly([[c, n]])}`, `f(x) = ${poly([[c, n]])} функциясының алғашқы функциясын табыңыз`), `${poly([[m, n + 1]])} + C`,
        [[`${poly([[c * n, n - 1]])} + C`, 'integ_as_deriv'], [`${poly([[c, n + 1]])} + C`, 'integ_no_divide'], [`${poly([[m, n]])} + C`], [`${poly([[c, n]])} + C`]],
        [tr('∫ xⁿ dx = xⁿ⁺¹ / (n + 1) + C: показатель увеличиваем на 1 и делим на новый показатель', '∫ xⁿ dx = xⁿ⁺¹ / (n + 1) + C: көрсеткішті 1-ге арттырып, жаңа көрсеткішке бөлеміз'),
          `${c} · ${xp(n + 1)} / ${n + 1} + C = ${poly([[m, n + 1]])} + C`]);
    },

    planmet(r) {
      const v = ri(r, 0, 3), cm = tr('см', 'см');
      if (v <= 1) {
        const [p, q, c] = pick(r, TRIPLES.slice(0, 4)), k = ri(r, 1, 2), a = p * k, b = q * k, h = c * k;
        if (v === 0) {
          return build('planmet', tr(`Катеты прямоугольного треугольника равны ${a} см и ${b} см. Найдите гипотенузу.`, `Тікбұрышты үшбұрыштың катеттері ${a} см және ${b} см. Гипотенузасын табыңыз.`), `${h} ${cm}`,
            [[`${a + b} ${cm}`, 'pyth_add'], [`${h * h} ${cm}`], [`${a * b / 2} ${cm}`], [`${a * b} ${cm}`]],
            [tr('Теорема Пифагора: c² = a² + b²', 'Пифагор теоремасы: c² = a² + b²'), `c² = ${a * a} + ${b * b} = ${h * h}`, `c = ${h} ${cm}`]);
        }
        return build('planmet', tr(`Гипотенуза равна ${h} см, один катет — ${a} см. Найдите второй катет.`, `Гипотенуза ${h} см, бір катет — ${a} см. Екінші катетті табыңыз.`), `${b} ${cm}`,
          [[`√${h * h + a * a} ${cm}`, 'pyth_leg'], [`${h - a} ${cm}`], [`${h + a} ${cm}`]],
          [tr('Катет: a² = c² − b²', 'Катет: a² = c² − b²'), `${h * h} − ${a * a} = ${b * b}`, `${b} ${cm}`]);
      }
      if (v === 2) {
        const a = 2 * ri(r, 2, 8), h = ri(r, 3, 12);
        return build('planmet', tr(`Найдите площадь треугольника со стороной ${a} см и высотой ${h} см, проведённой к этой стороне.`, `Қабырғасы ${a} см және осы қабырғаға түсірілген биіктігі ${h} см болатын үшбұрыштың ауданын табыңыз.`), `${a * h / 2} ${cm}²`,
          [[`${a * h} ${cm}²`, 'tri_area_half'], [`${a + h} ${cm}²`], [`${(a + h) * 2} ${cm}²`], [`${a * h / 2 + a} ${cm}²`], [`${a * h + a} ${cm}²`]],
          [tr('Площадь треугольника: S = a · h / 2', 'Үшбұрыштың ауданы: S = a · h / 2'), `S = ${a} · ${h} / 2 = ${a * h / 2} ${cm}²`]);
      }
      const k = ri(r, 2, 4), S = ri(r, 2, 9);
      return build('planmet', tr(`Треугольники подобны с коэффициентом ${k}. Площадь меньшего равна ${S} см². Найдите площадь большего.`, `Үшбұрыштар ұқсас, ұқсастық коэффициенті ${k}. Кішісінің ауданы ${S} см². Үлкенінің ауданын табыңыз.`), `${S * k * k} ${cm}²`,
        [[`${S * k} ${cm}²`, 'sim_area'], [`${S * k ** 3} ${cm}²`], [`${S + k} ${cm}²`], [`${S * k + 1} ${cm}²`], [`${S * k * k + k} ${cm}²`]],
        [tr('Площади подобных фигур относятся как k²', 'Ұқсас фигуралардың аудандарының қатынасы k²-қа тең'), `k² = ${k * k}`, `S = ${S} · ${k * k} = ${S * k * k} ${cm}²`]);
    }
  };
  Object.assign(T.GENERATORS, G);
})();
